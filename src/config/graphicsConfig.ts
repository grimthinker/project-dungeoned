// Актуальная рабочая копия конфигурации (изменяется в рантайме через SettingsManager)
export const GRAPHICS_CONFIG = fastClone(DEFAULT_GRAPHICS_CONFIG);

/**
 * Полуразмер охвата теневой камеры (в метрах) для текущего зума камеры.
 *
 * Единственный источник правды для всех, кому нужен радиус теней: сам рендерер
 * (позиционирует теневую камеру) и отсечение теней у чанков рельефа. Дублировать
 * эту формулу в двух местах нельзя — разъедутся, и чанки начнут отбрасывать
 * тени там, где их ещё видно.
 */
export function computeShadowBounds(cameraScale: number): number {
  const cfg = GRAPHICS_CONFIG.shadows;
  const dist = Math.max(4, 18 / cameraScale);
  return Math.max(cfg.minBounds, Math.min(cfg.maxBounds, dist * cfg.frustumMargin));
}
